import { useCallback, useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { apiFetch, downloadBlob } from "../api.js";
import { useToast } from "../components/Toast.jsx";
import { VerdictBadge } from "../components/VerdictBadge.jsx";
import DataTable from "../components/DataTable.jsx";

/*
 * AI Report Center — parity target index.html #reportsPage + downloadReport().
 * Pick any stored scan and POST /export-report (backend/main.py:1363, takes a
 * free-form dict) to stream back a forensic PDF. The body mirrors the field
 * mapping history_report_pdf uses (main.py:1495-1504) so both report paths
 * produce the same document. Batch runs export from the Batch panel itself
 * (their jobs are in-memory, keyed by job_id — there is no endpoint that
 * enumerates them later).
 */
export default function Reports() {
  const { push } = useToast();
  const [rows, setRows] = useState([]);
  const [loaded, setLoaded] = useState(false);
  const [busyId, setBusyId] = useState(null);

  const load = useCallback(async () => {
    try {
      const data = await apiFetch("/history?limit=50");
      setRows(Array.isArray(data) ? data : []);
    } catch (err) {
      push("error", err.message || "Could not load scan history.");
    } finally {
      setLoaded(true);
    }
  }, [push]);

  useEffect(() => {
    load();
  }, [load]);

  async function generate(row) {
    setBusyId(row.id);
    try {
      await downloadBlob("/export-report", `NexGuard_Report_${row.id}.pdf`, {
        method: "POST",
        body: {
          module: row.module,
          target: row.target,
          url: row.target,
          verdict: row.verdict,
          risk_score: row.score,
          score: row.score,
          summary: row.summary || "",
          ai_explanation: row.summary || "",
        },
      });
    } catch (err) {
      push("error", err.message || "Report generation failed.");
    } finally {
      setBusyId(null);
    }
  }

  const columns = [
    {
      key: "timestamp",
      label: "Time",
      render: (r) => <span className="text-xs text-muted">{String(r.timestamp || "").replace("T", " ")}</span>,
    },
    { key: "module", label: "Module" },
    { key: "target", label: "Target" },
    { key: "verdict", label: "Verdict", render: (r) => <VerdictBadge verdict={r.verdict} /> },
    { key: "score", label: "Risk" },
    {
      key: "action",
      label: "Action",
      sortable: false,
      render: (r) => (
        <button
          type="button"
          onClick={() => generate(r)}
          disabled={busyId === r.id}
          className="rounded-md border border-border bg-panel-2 px-2 py-1 text-xs font-medium text-text transition-colors hover:text-accent disabled:opacity-60 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
        >
          {busyId === r.id ? "Generating…" : "📄 Generate PDF"}
        </button>
      ),
    },
  ];

  return (
    <div className="space-y-4">
      <header className="space-y-1">
        <h1 className="text-xl font-semibold">Reports</h1>
        <p className="text-sm text-muted">
          Threat history and downloadable forensic reports generated by NexGuard AI.
        </p>
      </header>

      <div className="rounded-lg border border-border bg-panel p-3 text-sm text-muted">
        Looking for batch reports? CSV/PDF exports live on the{" "}
        <Link to="/scan?type=batch" className="font-medium text-accent hover:underline">
          Batch scanner
        </Link>{" "}
        right after a run finishes.
      </div>

      {loaded && rows.length === 0 ? (
        <p className="py-10 text-center text-sm text-muted">
          No scans to report on yet. Run a scan first — every result can be exported here.
        </p>
      ) : (
        <DataTable columns={columns} rows={rows} rowKey={(r) => r.id} />
      )}
    </div>
  );
}
